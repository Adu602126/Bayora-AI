export type TranslationKey = keyof typeof translations.en;

export function useTranslation(lang: Language) {
  return (key: TranslationKey): string => {
    if (lang === 'mr') {
      return (MARATHI[key] as string) || (translations.en[key] as string) || key;
    }
    return (translations[lang as 'en' | 'hi'][key] as string) || (translations.en[key] as string) || key;
  };
}

